# break statement
for i in range(12):
    if(i==8):
        break 
    print("5 x",i,"=",5*(i)) 
#5 x 0 = 0    
# 5 x 1 = 5
# 5 x 2 = 10
# 5 x 3 = 15
# 5 x 4 = 20
# 5 x 5 = 25
# 5 x 6 = 30
# 5 x 7 = 35


#continue statement
for i in range(12):
    if(i==8):
        continue
    print("2 x",i,"=",2*i)
# 2 x 0 = 0
# 2 x 1 = 2
# 2 x 2 = 4
# 2 x 3 = 6
# 2 x 4 = 8
